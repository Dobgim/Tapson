export const products: Product[] = seeds.map((seed) => {
  const title = [seed.year, seed.make, seed.model, seed.trim].filter(Boolean).join(" ");
  return {
    ...seed,
    slug: seed.id,
    title,
    // Three generated angles per unit; swapping in photography is a path change.
    images: [1, 2, 3].map((n) => `/images/products/${seed.id}-${n}.webp`),
    monthlyPayment: estimatedPayment(seed.price),
    savings: seed.msrp ? seed.msrp - seed.price : 0,
  };
});

export const productBySlug = new Map(products.map((p) => [p.slug, p]));

export const makes = Array.from(new Set(products.map((p) => p.make))).sort();

export const years = Array.from(new Set(products.map((p) => p.year))).sort((a, b) => b - a);

export const priceBounds = {
  min: 0,
  max: Math.ceil(Math.max(...products.map((p) => p.price)) / 5000) * 5000,
};

export function featuredProducts() {
  return products.filter((p) => p.featured);
}

export function specialProducts() {
  return products.filter((p) => p.special);
}

export function relatedProducts(product: Product, limit = 4) {
  const sameCategory = products.filter(
    (p) => p.category === product.category && p.id !== product.id,
  );
  const fallback = products.filter(
    (p) => p.category !== product.category && p.id !== product.id,
  );
  return [...sameCategory, ...fallback].slice(0, limit);
}
